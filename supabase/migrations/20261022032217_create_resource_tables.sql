-- The curated resource library, moved out of public/resources.json.
--
-- Column set mirrors schema/resource-schema.json field for field. Nullability,
-- vocabularies and invariants are NOT declared here: they live in the generated
-- *_resource_constraints.sql migration (scripts/gen-supabase-constraints.py), so
-- the JSON stays the one home of the contract. A NULL column means the field is
-- absent from the record, except for fields the schema lists as nullable.
create table public.resources (
  id text primary key,
  -- File order of the old resources.json; the export sorts by it so the
  -- generated file keeps a stable, append-at-the-end order.
  seq bigint generated by default as identity unique,
  -- 'proposed' rows (new routine finds) stay out of the published snapshot
  -- until approved in the #admin review queue.
  status text not null default 'live' check (status in ('proposed', 'live')),

  topic_title text,
  description text,
  url text,
  publisher_creator text,
  -- Text because the vocabulary mixes numeric grades with named ones ("K").
  -- The export turns digit strings back into JSON numbers.
  grade_level text[],
  grade_band text,
  subject text,
  strand text[],
  curriculum_expectations text[],
  province text,
  jurisdiction text,
  modality text[],
  resource_type text,
  access_type text,
  is_paid boolean,
  accessibility text[],
  metadata jsonb,

  language text,
  year_published integer,
  instructional_modes text[],
  usage_notes text,
  pedagogical_function text,
  estimated_minutes integer,
  is_collection boolean,
  suppressed boolean,
  decomposed boolean,
  tags text[],

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index resources_subject_idx on public.resources (subject);
create index resources_status_idx on public.resources (status);

-- ── Audit log ────────────────────────────────────────────────────────────────
-- Replaces "git history is the audit log". One row per changed resource row,
-- written by trigger so no write path can skip it. Writers tag their work with
--   select set_config('mk.actor', 'refresh-routine', true);
--   select set_config('mk.batch_id', gen_random_uuid()::text, true);
-- inside the transaction; revert_batch() undoes one batch.
create table public.resource_revisions (
  rev_id bigint generated always as identity primary key,
  resource_id text not null,
  op text not null check (op in ('insert', 'update', 'delete')),
  before jsonb,
  after jsonb,
  actor text not null,
  batch_id uuid,
  changed_at timestamptz not null default now()
);

create index resource_revisions_resource_idx on public.resource_revisions (resource_id, rev_id);
create index resource_revisions_batch_idx on public.resource_revisions (batch_id) where batch_id is not null;

create function public.resources_touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end
$$;

create trigger resources_touch_updated_at
  before update on public.resources
  for each row execute function public.resources_touch_updated_at();

-- security definer so the log is written whatever role made the change.
create function public.resources_log_revision()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor text := coalesce(nullif(current_setting('mk.actor', true), ''), session_user);
  v_batch uuid := nullif(current_setting('mk.batch_id', true), '')::uuid;
begin
  if tg_op = 'INSERT' then
    insert into public.resource_revisions (resource_id, op, before, after, actor, batch_id)
    values (new.id, 'insert', null, to_jsonb(new), v_actor, v_batch);
  elsif tg_op = 'UPDATE' then
    -- A no-op write (e.g. an upsert of identical content) is not a revision.
    if (to_jsonb(old) - 'updated_at') = (to_jsonb(new) - 'updated_at') then
      return null;
    end if;
    insert into public.resource_revisions (resource_id, op, before, after, actor, batch_id)
    values (new.id, 'update', to_jsonb(old), to_jsonb(new), v_actor, v_batch);
  else
    insert into public.resource_revisions (resource_id, op, before, after, actor, batch_id)
    values (old.id, 'delete', to_jsonb(old), null, v_actor, v_batch);
  end if;
  return null;
end
$$;

create trigger resources_log_revision
  after insert or update or delete on public.resources
  for each row execute function public.resources_log_revision();

-- Undo one batch, newest change first. Refuses (unless p_force) when a later
-- revision outside the batch touched the same resource, since reverting would
-- silently clobber that later work. The revert is itself a logged batch.
create function public.revert_batch(p_batch uuid, p_force boolean default false)
returns integer
language plpgsql
set search_path = ''
as $$
declare
  r public.resource_revisions;
  v_cols text;
  v_conflicts text;
  v_count integer := 0;
begin
  if not p_force then
    select string_agg(distinct later.resource_id, ', ') into v_conflicts
    from public.resource_revisions b
    join public.resource_revisions later
      on later.resource_id = b.resource_id
     and later.rev_id > b.rev_id
     and later.batch_id is distinct from p_batch
    where b.batch_id = p_batch;
    if v_conflicts is not null then
      raise exception 'revert_batch: changed again after batch %: %', p_batch, v_conflicts
        using hint = 'pass p_force => true to revert anyway';
    end if;
  end if;

  perform set_config('mk.actor', 'revert:' || p_batch::text, true);
  perform set_config('mk.batch_id', gen_random_uuid()::text, true);

  select string_agg(format('%I', column_name), ', ' order by ordinal_position) into v_cols
  from information_schema.columns
  where table_schema = 'public' and table_name = 'resources';

  for r in
    select * from public.resource_revisions where batch_id = p_batch order by rev_id desc
  loop
    if r.op = 'insert' then
      delete from public.resources where id = r.resource_id;
    elsif r.op = 'delete' then
      insert into public.resources
      select * from jsonb_populate_record(null::public.resources, r.before);
    else
      execute format(
        'update public.resources t set (%1$s) = (select %1$s from jsonb_populate_record(null::public.resources, $1)) where t.id = $2',
        v_cols
      ) using r.before, r.resource_id;
    end if;
    v_count := v_count + 1;
  end loop;

  return v_count;
end
$$;

-- ── Removed-row archive ──────────────────────────────────────────────────────
-- Replaces public/removed-resources.json. No foreign key: the archive has to
-- outlive the row it describes.
create table public.removed_resources (
  archive_id bigint generated always as identity primary key,
  resource_id text not null,
  record jsonb not null,
  reason text not null default '',
  removed_by text not null,
  removed_at timestamptz not null default now(),
  batch_id uuid
);

create index removed_resources_resource_idx on public.removed_resources (resource_id);

-- ── Link-health ledger ───────────────────────────────────────────────────────
-- Append-only; replaces link-health.json and health-changelog.json. A resource
-- with no rows is "unchecked". link_status is NULL for a pass that yields no
-- verdict (e.g. a content-hash sweep). The dead vs blocked/error split is kept:
-- blocked/error are about our request, never about the resource, and nothing is
-- auto-suppressed on any verdict.
create table public.link_checks (
  check_id bigint generated always as identity primary key,
  resource_id text not null,
  url text not null,
  checked_at timestamptz not null default now(),
  method text not null check (method in ('dns', 'http', 'webfetch', 'content')),
  link_status text,
  http_status integer,
  final_url text,
  dns_ok boolean,
  content_hash text,
  reason text,
  actor text not null default session_user
);

create index link_checks_resource_idx on public.link_checks (resource_id, checked_at desc);

-- ── Access ───────────────────────────────────────────────────────────────────
-- RLS everywhere. Only live resources are readable without the service key;
-- that is the same data the public site serves today. Every write goes through
-- the service role (Vercel functions, build/routine scripts).
alter table public.resources enable row level security;
alter table public.resource_revisions enable row level security;
alter table public.removed_resources enable row level security;
alter table public.link_checks enable row level security;

do $$
begin
  -- Supabase grants anon/authenticated everything on new objects by default;
  -- strip it so RLS is not the only line of defence. Guarded so the migration
  -- also runs on a plain Postgres (supabase/tests).
  if exists (select 1 from pg_roles where rolname = 'anon') then
    revoke all on public.resources, public.resource_revisions, public.removed_resources, public.link_checks
      from anon, authenticated;
    revoke all on function public.revert_batch(uuid, boolean) from public, anon, authenticated;
    grant select on public.resources to anon, authenticated;
  else
    revoke all on function public.revert_batch(uuid, boolean) from public;
  end if;
end
$$;

create policy "live resources are public"
  on public.resources for select
  using (status = 'live');

-- The published snapshot the build exports. security_invoker so it is bound by
-- the policy above rather than by the view owner's rights.
create view public.published_resources
with (security_invoker = true)
as
select
  seq, id, topic_title, description, url, publisher_creator, grade_level, grade_band,
  subject, strand, curriculum_expectations, province, jurisdiction, modality,
  resource_type, access_type, is_paid, accessibility, metadata, language,
  year_published, instructional_modes, usage_notes, pedagogical_function,
  estimated_minutes, is_collection, suppressed, decomposed, tags
from public.resources
where status = 'live';

do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    revoke all on public.published_resources from anon, authenticated;
    grant select on public.published_resources to anon, authenticated;
  end if;
end
$$;
